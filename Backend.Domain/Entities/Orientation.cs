namespace UCR.ECCI.PI.ThemePark.Backend.Domain.Entities;

/// <summary>
/// Represents the orientation of a learning component in 3D space.
/// </summary>
public enum Orientation
{
    /// <summary>
    /// Facing North (positive Z direction).
    /// </summary>
    North,

    /// <summary>
    /// Facing South (negative Z direction).
    /// </summary>
    South,

    /// <summary>
    /// Facing East (positive X direction).
    /// </summary>
    East,

    /// <summary>
    /// Facing West (negative X direction).
    /// </summary>
    West
}
