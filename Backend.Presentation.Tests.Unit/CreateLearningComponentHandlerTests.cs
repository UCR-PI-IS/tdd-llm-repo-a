using Moq;
using NUnit.Framework;
using UCR.ECCI.PI.ThemePark.Backend.Application.Services;
using UCR.ECCI.PI.ThemePark.Backend.Domain.Entities;
using UCR.ECCI.PI.ThemePark.Backend.Domain.Exceptions;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Dtos;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Handlers;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Responses;

namespace UCR.ECCI.PI.ThemePark.Backend.Presentation.Tests.Unit;

/// <summary>
/// Unit tests for <see cref="CreateLearningComponentHandler.HandleAsync"/>.
/// Covers CPD-LC-001-009 Presentation-001 through Presentation-004.
/// </summary>
[TestFixture]
public class CreateLearningComponentHandlerTests
{
    private Mock<ILearningComponentService> _mockService = null!;

    [SetUp]
    public void SetUp()
    {
        _mockService = new Mock<ILearningComponentService>();
    }

    [TearDown]
    public void TearDown()
    {
        _mockService.VerifyAll();
    }

    /// <summary>
    /// CPD-LC-001-009 Presentation-001: Verify that creating a component without an ID
    /// returns the auto-generated ID in the response with an appropriate message.
    /// </summary>
    [Test]
    [Description("CPD-LC-001-009 Presentation-001: Creating component without ID returns auto-generated ID")]
    public async Task HandleAsync_WithoutId_ReturnsAutoGeneratedId()
    {
        // Arrange
        var dto = new CreateLearningComponentDto(
            ComponentId: null,
            LearningSpaceId: "LS-001",
            Width: 1.5f, Height: 1.0f, Depth: 0.5f,
            X: 10.0f, Y: 5.0f, Z: 0.0f,
            Orientation: "North");

        var createdComponent = new LearningComponent(
            "COMP-12345", "LS-001", 1.5f, 1.0f, 0.5f, 10.0f, 5.0f, 0.0f, "North");

        _mockService
            .Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ReturnsAsync(createdComponent);

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, dto);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result.ComponentId, Is.EqualTo("COMP-12345"));
            Assert.That(result.Message, Does.Contain("auto-generated"));
        });
    }

    /// <summary>
    /// CPD-LC-001-009 Presentation-002: Verify that creating a component with an explicit ID
    /// returns the provided ID in the response.
    /// </summary>
    [Test]
    [Description("CPD-LC-001-009 Presentation-002: Creating component with explicit ID returns provided ID")]
    public async Task HandleAsync_WithExplicitId_ReturnsProvidedId()
    {
        // Arrange
        var dto = new CreateLearningComponentDto(
            ComponentId: "COMP-EXPLICIT-001",
            LearningSpaceId: "LS-001",
            Width: 1.5f, Height: 1.0f, Depth: 0.5f,
            X: 10.0f, Y: 5.0f, Z: 0.0f,
            Orientation: "North");

        var createdComponent = new LearningComponent(
            "COMP-EXPLICIT-001", "LS-001", 1.5f, 1.0f, 0.5f, 10.0f, 5.0f, 0.0f, "North");

        _mockService
            .Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ReturnsAsync(createdComponent);

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, dto);

        // Assert
        Assert.That(result.ComponentId, Is.EqualTo("COMP-EXPLICIT-001"));
    }

    /// <summary>
    /// CPD-LC-001-009 Presentation-003: Verify that attempting to create a component with a
    /// duplicate ID returns a 409 Conflict response with an appropriate error message.
    /// </summary>
    [Test]
    [Description("CPD-LC-001-009 Presentation-003: Duplicate ID returns 409 Conflict")]
    public async Task HandleAsync_DuplicateId_ReturnsConflict()
    {
        // Arrange
        var dto = new CreateLearningComponentDto(
            ComponentId: "COMP-DUPLICATE",
            LearningSpaceId: "LS-001",
            Width: 1.5f, Height: 1.0f, Depth: 0.5f,
            X: 10.0f, Y: 5.0f, Z: 0.0f,
            Orientation: "North");

        _mockService
            .Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new DuplicateIdException("Component with ID 'COMP-DUPLICATE' already exists"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, dto);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result.StatusCode, Is.EqualTo(409));
            Assert.That(result.ErrorMessage, Does.Contain("already exists"));
        });
    }

    /// <summary>
    /// CPD-LC-001-009 Presentation-004: Verify that creating a component with invalid data
    /// returns a 400 Bad Request response with an appropriate error message.
    /// </summary>
    [Test]
    [Description("CPD-LC-001-009 Presentation-004: Invalid data returns 400 Bad Request")]
    public async Task HandleAsync_InvalidData_ReturnsBadRequest()
    {
        // Arrange
        var dto = new CreateLearningComponentDto(
            ComponentId: null,
            LearningSpaceId: "LS-001",
            Width: -1.5f, Height: 1.0f, Depth: 0.5f,
            X: 10.0f, Y: 5.0f, Z: 0.0f,
            Orientation: "North");

        _mockService
            .Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new ValidationException("Width must be positive"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, dto);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result.StatusCode, Is.EqualTo(400));
            Assert.That(result.ErrorMessage, Does.Contain("Width"));
        });
    }
}
