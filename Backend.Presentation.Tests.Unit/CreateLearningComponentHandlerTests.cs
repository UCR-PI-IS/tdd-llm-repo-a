using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Http.HttpResults;
using Moq;
using NUnit.Framework;
using UCR.ECCI.PI.ThemePark.Backend.Application.Exceptions;
using UCR.ECCI.PI.ThemePark.Backend.Application.Services;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Handlers;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Responses;

namespace UCR.ECCI.PI.ThemePark.Backend.Presentation.Tests.Unit;

/// <summary>
/// Unit tests for <see cref="CreateLearningComponentHandler.HandleAsync"/>.
/// Covers intents Presentation-001 through Presentation-004 for story CPD-LC-001-009.
/// </summary>
[TestFixture]
public class CreateLearningComponentHandlerTests
{
    private Mock<ILearningComponentService> _mockService = null!;

    [SetUp]
    public void SetUp()
    {
        _mockService = new Mock<ILearningComponentService>();
    }

    [TearDown]
    public void TearDown()
    {
        _mockService.VerifyAll();
    }

    /// <summary>
    /// Presentation-001: Verify that creating a component without an ID returns the auto-generated ID in the response.
    /// </summary>
    [Test]
    [Description("Presentation-001: Verify that creating a component without an ID returns the auto-generated ID in the response")]
    public async Task HandleAsync_WithoutId_ReturnsAutoGeneratedId()
    {
        // Arrange
        var requestWithoutId = new CreateComponentRequest
        {
            LearningSpaceId = "LS-001",
            Width = 1.5f,
            Height = 1.0f,
            Depth = 0.5f,
            X = 10.0f,
            Y = 5.0f,
            Z = 0.0f,
            Orientation = "North"
        };

        _mockService.Setup(x => x.CreateComponentAsync(requestWithoutId))
            .ReturnsAsync(new CreateComponentResult
            {
                ComponentId = "COMP-12345",
                Message = "Component created with auto-generated ID"
            });

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, requestWithoutId);

        // Assert
        Assert.That(result, Is.TypeOf<Created<CreateComponentResponse>>());
        var createdResult = result as Created<CreateComponentResponse>;
        Assert.That(createdResult!.Value!.ComponentId, Is.EqualTo("COMP-12345"));
    }

    /// <summary>
    /// Presentation-002: Verify that creating a component with an explicit ID returns the provided ID in the response.
    /// </summary>
    [Test]
    [Description("Presentation-002: Verify that creating a component with an explicit ID returns the provided ID in the response")]
    public async Task HandleAsync_WithExplicitId_ReturnsProvidedId()
    {
        // Arrange
        var requestWithExplicitId = new CreateComponentRequest
        {
            ComponentId = "COMP-EXPLICIT-001",
            LearningSpaceId = "LS-001",
            Width = 1.5f,
            Height = 1.0f,
            Depth = 0.5f,
            X = 10.0f,
            Y = 5.0f,
            Z = 0.0f,
            Orientation = "North"
        };

        _mockService.Setup(x => x.CreateComponentAsync(requestWithExplicitId))
            .ReturnsAsync(new CreateComponentResult
            {
                ComponentId = "COMP-EXPLICIT-001",
                Message = "Component created with explicit ID"
            });

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, requestWithExplicitId);

        // Assert
        Assert.That(result, Is.TypeOf<Created<CreateComponentResponse>>());
        var createdResult = result as Created<CreateComponentResponse>;
        Assert.That(createdResult!.Value!.ComponentId, Is.EqualTo("COMP-EXPLICIT-001"));
    }

    /// <summary>
    /// Presentation-003: Verify that attempting to create a component with a duplicate ID returns a 409 Conflict response.
    /// </summary>
    [Test]
    [Description("Presentation-003: Verify that attempting to create a component with a duplicate ID returns a 409 Conflict response")]
    public async Task HandleAsync_WithDuplicateId_ReturnsConflict()
    {
        // Arrange
        var requestWithDuplicateId = new CreateComponentRequest
        {
            ComponentId = "COMP-DUPLICATE",
            LearningSpaceId = "LS-001",
            Width = 1.5f,
            Height = 1.0f,
            Depth = 0.5f,
            X = 10.0f,
            Y = 5.0f,
            Z = 0.0f,
            Orientation = "North"
        };

        _mockService.Setup(x => x.CreateComponentAsync(requestWithDuplicateId))
            .ThrowsAsync(new DuplicateIdException("COMP-DUPLICATE already exists"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, requestWithDuplicateId);

        // Assert
        Assert.That(result, Is.TypeOf<Conflict<ErrorResponse>>());
        var conflictResult = result as Conflict<ErrorResponse>;
        Assert.That(conflictResult!.Value!.StatusCode, Is.EqualTo(409));
        Assert.That(conflictResult.Value.Message, Does.Contain("already exists"));
    }

    /// <summary>
    /// Presentation-004: Verify that creating a component with invalid data returns a 400 Bad Request response.
    /// </summary>
    [Test]
    [Description("Presentation-004: Verify that creating a component with invalid data returns a 400 Bad Request response")]
    public async Task HandleAsync_WithInvalidData_ReturnsBadRequest()
    {
        // Arrange
        var requestWithInvalidData = new CreateComponentRequest
        {
            LearningSpaceId = "LS-001",
            Width = -1.5f,
            Height = 1.0f,
            Depth = 0.5f,
            X = 10.0f,
            Y = 5.0f,
            Z = 0.0f,
            Orientation = "North"
        };

        _mockService.Setup(x => x.CreateComponentAsync(requestWithInvalidData))
            .ThrowsAsync(new ValidationException("Width must be positive"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, requestWithInvalidData);

        // Assert
        Assert.That(result, Is.TypeOf<BadRequest<ErrorResponse>>());
        var badRequestResult = result as BadRequest<ErrorResponse>;
        Assert.That(badRequestResult!.Value!.StatusCode, Is.EqualTo(400));
        Assert.That(badRequestResult.Value.Message, Does.Contain("Width"));
    }
}
