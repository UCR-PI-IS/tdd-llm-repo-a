using Moq;
using NUnit.Framework;
using UCR.ECCI.PI.ThemePark.Backend.Application.Exceptions;
using UCR.ECCI.PI.ThemePark.Backend.Application.Services;
using UCR.ECCI.PI.ThemePark.Backend.Domain.Exceptions;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Handlers;

namespace UCR.ECCI.PI.ThemePark.Backend.Presentation.Tests.Unit;

/// <summary>
/// Unit tests for <see cref="CreateLearningComponentHandler.HandleAsync"/>.
/// Covers intents Presentation-001 through Presentation-004 from CPD-LC-001-009.
/// </summary>
[TestFixture]
public class CreateLearningComponentHandlerTests
{
    private Mock<ILearningComponentService> _mockService = null!;

    [SetUp]
    public void SetUp()
    {
        _mockService = new Mock<ILearningComponentService>();
    }

    [TearDown]
    public void TearDown()
    {
        _mockService.VerifyAll();
    }

    private static CreateComponentRequest CreateValidRequest(string? componentId = null)
    {
        return new CreateComponentRequest
        {
            ComponentId = componentId,
            LearningSpaceId = "LS-001",
            Width = 1.5f,
            Height = 1.0f,
            Depth = 0.5f,
            X = 10.0f,
            Y = 5.0f,
            Z = 0.0f,
            Orientation = "North"
        };
    }

    /// <summary>
    /// Presentation-001 (CPD-LC-001-009): Verify that creating a component without an ID
    /// returns the auto-generated ID in the response with a message indicating auto-generation.
    /// </summary>
    [Test]
    [Description("Presentation-001: Handler returns auto-generated ID with confirmation message")]
    public async Task HandleAsync_WithoutId_ReturnsAutoGeneratedId()
    {
        // Arrange
        var generatedId = "COMP-12345";
        var request = CreateValidRequest();

        _mockService
            .Setup(s => s.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ReturnsAsync(new CreateComponentResult
            {
                ComponentId = generatedId,
                Message = "Component created with auto-generated ID"
            });

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(
            _mockService.Object, request);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result.ComponentId, Is.EqualTo(generatedId));
            Assert.That(result.Message, Does.Contain("auto-generated"));
        });
    }

    /// <summary>
    /// Presentation-002 (CPD-LC-001-009): Verify that creating a component with an
    /// explicit ID returns the provided ID in the response.
    /// </summary>
    [Test]
    [Description("Presentation-002: Handler returns the explicit ID provided in the request")]
    public async Task HandleAsync_WithExplicitId_ReturnsProvidedId()
    {
        // Arrange
        var explicitId = "COMP-EXPLICIT-001";
        var request = CreateValidRequest(componentId: explicitId);

        _mockService
            .Setup(s => s.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ReturnsAsync(new CreateComponentResult
            {
                ComponentId = explicitId,
                Message = "Component created successfully"
            });

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(
            _mockService.Object, request);

        // Assert
        Assert.That(result.ComponentId, Is.EqualTo(explicitId));
    }

    /// <summary>
    /// Presentation-003 (CPD-LC-001-009): Verify that attempting to create a component
    /// with a duplicate ID returns a 409 Conflict response with an appropriate error message.
    /// </summary>
    [Test]
    [Description("Presentation-003: Duplicate ID returns 409 Conflict with error message")]
    public async Task HandleAsync_WithDuplicateId_ReturnsConflict()
    {
        // Arrange
        var request = CreateValidRequest(componentId: "COMP-DUP");

        _mockService
            .Setup(s => s.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new DuplicateIdException("Component ID already exists"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(
            _mockService.Object, request);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result.StatusCode, Is.EqualTo(409));
            Assert.That(result.ErrorMessage, Does.Contain("already exists"));
        });
    }

    /// <summary>
    /// Presentation-004 (CPD-LC-001-009): Verify that creating a component with invalid
    /// data returns a 400 Bad Request response with a validation error message.
    /// </summary>
    [Test]
    [Description("Presentation-004: Invalid data returns 400 Bad Request with validation message")]
    public async Task HandleAsync_WithInvalidData_ReturnsBadRequest()
    {
        // Arrange
        var request = new CreateComponentRequest
        {
            LearningSpaceId = "LS-001",
            Width = -1.5f,
            Height = 1.0f,
            Depth = 0.5f,
            X = 10.0f,
            Y = 5.0f,
            Z = 0.0f,
            Orientation = "North"
        };

        _mockService
            .Setup(s => s.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new ValidationException("Width must be positive"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(
            _mockService.Object, request);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result.StatusCode, Is.EqualTo(400));
            Assert.That(result.ErrorMessage, Does.Contain("Width"));
        });
    }
}
