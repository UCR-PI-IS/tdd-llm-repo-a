using Microsoft.AspNetCore.Http.HttpResults;
using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Routing;
using Moq;
using NUnit.Framework;
using UCR.ECCI.PI.ThemePark.Backend.Application.Services;
using UCR.ECCI.PI.ThemePark.Backend.Domain.Entities;
using UCR.ECCI.PI.ThemePark.Backend.Domain.Exceptions;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Dtos;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Handlers;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Endpoints;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Responses;

namespace UCR.ECCI.PI.ThemePark.Backend.Presentation.Tests.Unit;

/// <summary>
/// Unit tests for <see cref="CreateLearningComponentHandler.HandleAsync"/> and
/// <see cref="LearningComponentEndpoints.MapCreateComponentEndpoint"/>.
/// Covers intents Presentation-001 through Presentation-005 for CPD-LC-001-009.
/// </summary>
[TestFixture]
public class CreateLearningComponentHandlerTests
{
    private Mock<ILearningComponentService> _mockService = null!;

    // Valid test data
    private const string GeneratedComponentId = "COMP-12345";
    private const string ExplicitComponentId = "COMP-EXPLICIT-001";
    private const string ExistingComponentId = "COMP-EXISTING";
    private const string ValidLearningSpaceId = "LS-001";

    [SetUp]
    public void SetUp()
    {
        _mockService = new Mock<ILearningComponentService>();
    }

    [TearDown]
    public void TearDown()
    {
        _mockService.VerifyAll();
    }

    private static CreateLearningComponentDto CreateDtoWithoutId()
    {
        return new CreateLearningComponentDto(
            componentId: null,
            learningSpaceId: ValidLearningSpaceId,
            width: 1.5f,
            height: 1.0f,
            depth: 0.5f,
            x: 10.0f,
            y: 5.0f,
            z: 0.0f,
            orientation: "North");
    }

    private static CreateLearningComponentDto CreateDtoWithExplicitId(string componentId)
    {
        return new CreateLearningComponentDto(
            componentId: componentId,
            learningSpaceId: ValidLearningSpaceId,
            width: 1.5f,
            height: 1.0f,
            depth: 0.5f,
            x: 10.0f,
            y: 5.0f,
            z: 0.0f,
            orientation: "North");
    }

    private static CreateLearningComponentDto CreateDtoWithInvalidData()
    {
        return new CreateLearningComponentDto(
            componentId: null,
            learningSpaceId: ValidLearningSpaceId,
            width: -1.5f,
            height: 1.0f,
            depth: 0.5f,
            x: 10.0f,
            y: 5.0f,
            z: 0.0f,
            orientation: "North");
    }

    /// <summary>
    /// Presentation-001: Verify that creating a component without an ID returns the auto-generated ID in the response.
    /// </summary>
    [Test]
    [Description("Presentation-001: Verify that creating a component without an ID returns the auto-generated ID")]
    public async Task HandleAsync_WithoutId_ReturnsAutoGeneratedId()
    {
        // Arrange
        var dto = CreateDtoWithoutId();
        var component = new LearningComponent(GeneratedComponentId, ValidLearningSpaceId, 1.5f, 1.0f, 0.5f, 10.0f, 5.0f, 0.0f, "North");
        _mockService.Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>())).ReturnsAsync(component);

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, dto);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result.ComponentId, Is.EqualTo(GeneratedComponentId));
            Assert.That(result.Message, Does.Contain("auto-generated"));
        });
    }

    /// <summary>
    /// Presentation-002: Verify that creating a component with an explicit ID returns the provided ID in the response.
    /// </summary>
    [Test]
    [Description("Presentation-002: Verify that creating a component with an explicit ID returns the provided ID")]
    public async Task HandleAsync_WithExplicitId_ReturnsProvidedId()
    {
        // Arrange
        var dto = CreateDtoWithExplicitId(ExplicitComponentId);
        var component = new LearningComponent(ExplicitComponentId, ValidLearningSpaceId, 1.5f, 1.0f, 0.5f, 10.0f, 5.0f, 0.0f, "North");
        _mockService.Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>())).ReturnsAsync(component);

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, dto);

        // Assert
        Assert.That(result.ComponentId, Is.EqualTo(ExplicitComponentId));
    }

    /// <summary>
    /// Presentation-003: Verify that attempting to create a component with a duplicate ID returns a 409 Conflict response.
    /// </summary>
    [Test]
    [Description("Presentation-003: Verify that duplicate ID returns 409 Conflict response")]
    public async Task HandleAsync_DuplicateId_ReturnsConflict()
    {
        // Arrange
        var dto = CreateDtoWithExplicitId(ExistingComponentId);
        _mockService.Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new DuplicateIdException("already exists"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, dto);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result.StatusCode, Is.EqualTo(409));
            Assert.That(result.ErrorMessage, Does.Contain("already exists"));
        });
    }

    /// <summary>
    /// Presentation-004: Verify that creating a component with invalid data returns a 400 Bad Request response.
    /// </summary>
    [Test]
    [Description("Presentation-004: Verify that invalid data returns 400 Bad Request response")]
    public async Task HandleAsync_InvalidData_ReturnsBadRequest()
    {
        // Arrange
        var dto = CreateDtoWithInvalidData();
        _mockService.Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new ValidationException("Width must be positive"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, dto);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result.StatusCode, Is.EqualTo(400));
            Assert.That(result.ErrorMessage, Does.Contain("Width"));
        });
    }

    /// <summary>
    /// Testable implementation of IEndpointRouteBuilder that captures endpoint registrations.
    /// </summary>
    private class TestEndpointRouteBuilder : IEndpointRouteBuilder
    {
        public ICollection<EndpointDataSource> DataSources { get; } = new List<EndpointDataSource>();
        public IServiceProvider ServiceProvider { get; } = new Mock<IServiceProvider>().Object;
        
        public string? CapturedPattern { get; private set; }
        public Delegate? CapturedDelegate { get; private set; }
        public string? CapturedName { get; private set; }
        public bool OpenApiCalled { get; private set; }

        public IApplicationBuilder CreateApplicationBuilder()
        {
            throw new NotImplementedException();
        }

        public IEndpointRouteBuilder Map(string pattern, Delegate handler)
        {
            CapturedPattern = pattern;
            CapturedDelegate = handler;
            return this;
        }

        public void SetEndpointName(string name)
        {
            CapturedName = name;
        }

        public void MarkOpenApiCalled()
        {
            OpenApiCalled = true;
        }
    }

    /// <summary>
    /// Testable wrapper that intercepts RouteHandlerBuilder calls.
    /// </summary>
    private class TestRouteHandlerBuilder : IRouteHandlerBuilder
    {
        private readonly TestEndpointRouteBuilder _builder;

        public TestRouteHandlerBuilder(TestEndpointRouteBuilder builder)
        {
            _builder = builder;
        }

        public override IRouteHandlerBuilder WithName(string name)
        {
            _builder.SetEndpointName(name);
            return this;
        }

        public override IRouteHandlerBuilder WithOpenApi()
        {
            _builder.MarkOpenApiCalled();
            return this;
        }
    }

    /// <summary>
    /// Presentation-005: Verify that the POST endpoint for creating components is correctly mapped.
    /// Tests the endpoint registration by using a testable implementation that captures the calls.
    /// </summary>
    [Test]
    [Description("Presentation-005: Verify that the POST endpoint for creating components is correctly mapped")]
    public void MapCreateComponentEndpoint_MapsCorrectly()
    {
        // Arrange
        var testBuilder = new TestEndpointRouteBuilder();

        // Act - Call the method under test
        // Since MapPost is an extension method, we test the outcome indirectly
        // by verifying the endpoint is properly configured through integration
        var result = LearningComponentEndpoints.MapCreateComponentEndpoint(testBuilder);

        // Assert - Verify the route handler builder was returned
        Assert.That(result, Is.Not.Null, "MapCreateComponentEndpoint should return a route handler builder");
        
        // Verify the builder has the expected fluent API methods
        var builderWithName = result.WithName("TestName");
        Assert.That(builderWithName, Is.Not.Null, "WithName should return the builder for chaining");
        
        var builderWithOpenApi = result.WithOpenApi();
        Assert.That(builderWithOpenApi, Is.Not.Null, "WithOpenApi should return the builder for chaining");
    }
}
