using Moq;
using NUnit.Framework;
using UCR.ECCI.PI.ThemePark.Backend.Application.Services;
using UCR.ECCI.PI.ThemePark.Backend.Domain.Entities;
using UCR.ECCI.PI.ThemePark.Backend.Domain.Exceptions;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Dtos;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Handlers;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Responses;

namespace UCR.ECCI.PI.ThemePark.Backend.Presentation.Tests.Unit;

/// <summary>
/// Unit tests for <see cref="CreateLearningComponentHandler.HandleAsync"/>.
/// Covers CPD-LC-001-009 intents Presentation-001 through Presentation-004.
/// </summary>
[TestFixture]
public class CreateLearningComponentHandlerTests
{
    private Mock<ILearningComponentService> _mockService = null!;
    private CreateLearningComponentHandler _sut = null!;

    // Valid test data
    private const string ValidLearningSpaceId = "LS-001";
    private const float ValidWidth = 1.5f;
    private const float ValidHeight = 1.0f;
    private const float ValidDepth = 0.5f;
    private const float ValidX = 10.0f;
    private const float ValidY = 5.0f;
    private const float ValidZ = 0.0f;
    private const string ValidOrientation = "North";

    [SetUp]
    public void SetUp()
    {
        _mockService = new Mock<ILearningComponentService>();
        _sut = new CreateLearningComponentHandler(_mockService.Object);
    }

    [TearDown]
    public void TearDown()
    {
        _mockService.VerifyAll();
    }

    private static CreateLearningComponentDto CreateDtoWithoutId()
    {
        return new CreateLearningComponentDto(
            ComponentId: null,
            LearningSpaceId: ValidLearningSpaceId,
            Width: ValidWidth,
            Height: ValidHeight,
            Depth: ValidDepth,
            X: ValidX,
            Y: ValidY,
            Z: ValidZ,
            Orientation: ValidOrientation);
    }

    private static CreateLearningComponentDto CreateDtoWithExplicitId(string componentId)
    {
        return new CreateLearningComponentDto(
            ComponentId: componentId,
            LearningSpaceId: ValidLearningSpaceId,
            Width: ValidWidth,
            Height: ValidHeight,
            Depth: ValidDepth,
            X: ValidX,
            Y: ValidY,
            Z: ValidZ,
            Orientation: ValidOrientation);
    }

    /// <summary>
    /// CPD-LC-001-009 Presentation-001: Verify that creating a component without an ID
    /// returns the auto-generated ID in the response with an appropriate message.
    /// </summary>
    [Test]
    [Description("CPD-LC-001-009 Presentation-001: Handler returns auto-generated ID in response")]
    public async Task HandleAsync_WithoutId_ReturnsAutoGeneratedId()
    {
        // Arrange
        var dto = CreateDtoWithoutId();
        var component = new LearningComponent(
            "COMP-12345", ValidLearningSpaceId,
            ValidWidth, ValidHeight, ValidDepth,
            ValidX, ValidY, ValidZ,
            ValidOrientation);

        _mockService
            .Setup(s => s.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ReturnsAsync(component);

        // Act
        var result = await _sut.HandleAsync(dto);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result.ComponentId, Is.EqualTo("COMP-12345"));
            Assert.That(result.Message, Does.Contain("auto-generated"));
        });
    }

    /// <summary>
    /// CPD-LC-001-009 Presentation-002: Verify that creating a component with an explicit ID
    /// returns the provided ID in the response.
    /// </summary>
    [Test]
    [Description("CPD-LC-001-009 Presentation-002: Handler returns explicit ID in response")]
    public async Task HandleAsync_WithExplicitId_ReturnsProvidedId()
    {
        // Arrange
        var explicitId = "COMP-EXPLICIT-001";
        var dto = CreateDtoWithExplicitId(explicitId);
        var component = new LearningComponent(
            explicitId, ValidLearningSpaceId,
            ValidWidth, ValidHeight, ValidDepth,
            ValidX, ValidY, ValidZ,
            ValidOrientation);

        _mockService
            .Setup(s => s.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ReturnsAsync(component);

        // Act
        var result = await _sut.HandleAsync(dto);

        // Assert
        Assert.That(result.ComponentId, Is.EqualTo(explicitId));
    }

    /// <summary>
    /// CPD-LC-001-009 Presentation-003: Verify that attempting to create a component with a
    /// duplicate ID returns a 409 Conflict response with an appropriate error message.
    /// </summary>
    [Test]
    [Description("CPD-LC-001-009 Presentation-003: Duplicate ID returns 409 Conflict")]
    public async Task HandleAsync_DuplicateId_Returns409Conflict()
    {
        // Arrange
        var dto = CreateDtoWithExplicitId("COMP-DUPLICATE");

        _mockService
            .Setup(s => s.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new DuplicateIdException("Component with ID 'COMP-DUPLICATE' already exists"));

        // Act
        var result = await _sut.HandleAsync(dto);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result.StatusCode, Is.EqualTo(409));
            Assert.That(result.ErrorMessage, Does.Contain("already exists"));
        });
    }

    /// <summary>
    /// CPD-LC-001-009 Presentation-004: Verify that creating a component with invalid data
    /// returns a 400 Bad Request response with an appropriate error message.
    /// </summary>
    [Test]
    [Description("CPD-LC-001-009 Presentation-004: Invalid data returns 400 Bad Request")]
    public async Task HandleAsync_InvalidData_Returns400BadRequest()
    {
        // Arrange
        var dto = new CreateLearningComponentDto(
            ComponentId: null,
            LearningSpaceId: ValidLearningSpaceId,
            Width: -1.5f,
            Height: ValidHeight,
            Depth: ValidDepth,
            X: ValidX,
            Y: ValidY,
            Z: ValidZ,
            Orientation: ValidOrientation);

        _mockService
            .Setup(s => s.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new ValidationException("Width must be positive"));

        // Act
        var result = await _sut.HandleAsync(dto);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result.StatusCode, Is.EqualTo(400));
            Assert.That(result.ErrorMessage, Does.Contain("Width"));
        });
    }
}
