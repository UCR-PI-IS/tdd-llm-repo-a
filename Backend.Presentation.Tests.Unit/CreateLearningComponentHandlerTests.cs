using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Http.HttpResults;
using Moq;
using NUnit.Framework;
using UCR.ECCI.PI.ThemePark.Backend.Application.Services;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Dtos;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Handlers;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Responses;

namespace UCR.ECCI.PI.ThemePark.Backend.Presentation.Tests.Unit;

/// <summary>
/// Unit tests for <see cref="CreateLearningComponentHandler.HandleAsync"/>.
/// Covers intents Presentation-001 through Presentation-004 for CPD-LC-001-009.
/// </summary>
[TestFixture]
public class CreateLearningComponentHandlerTests
{
    private Mock<ILearningComponentService> _mockService = null!;

    // Valid test data
    private const string GeneratedComponentId = "COMP-12345";
    private const string ExplicitComponentId = "COMP-EXPLICIT-001";
    private const string ValidLearningSpaceId = "LS-001";

    [SetUp]
    public void SetUp()
    {
        _mockService = new Mock<ILearningComponentService>();
    }

    [TearDown]
    public void TearDown()
    {
        _mockService.VerifyAll();
    }

    /// <summary>
    /// Presentation-001: Verify that creating a component without an ID returns the auto-generated ID in the response.
    /// </summary>
    [Test]
    [Description("Presentation-001: Verify handler returns auto-generated ID when no explicit ID provided")]
    public async Task HandleAsync_WithoutExplicitId_ReturnsAutoGeneratedId()
    {
        // Arrange
        var request = new CreateLearningComponentRequest(
            learningSpaceId: ValidLearningSpaceId,
            width: 1.5f,
            height: 1.0f,
            depth: 0.5f,
            x: 10.0f,
            y: 5.0f,
            z: 0.0f,
            orientation: "North",
            componentId: null);

        var serviceResult = new CreateComponentResult(GeneratedComponentId);

        _mockService
            .Setup(s => s.CreateComponentAsync(It.Is<CreateComponentRequest>(r => r.ComponentId == null)))
            .ReturnsAsync(serviceResult);

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, request);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result, Is.TypeOf<Ok<CreateLearningComponentResponse>>())
                .Or.TypeOf<Created<CreateLearningComponentResponse>>();
            var successResult = result as Ok<CreateLearningComponentResponse>;
            if (successResult != null)
            {
                Assert.That(successResult.Value!.ComponentId, Is.EqualTo(GeneratedComponentId));
            }
        });
    }

    /// <summary>
    /// Presentation-002: Verify that creating a component with an explicit ID returns the provided ID in the response.
    /// </summary>
    [Test]
    [Description("Presentation-002: Verify handler returns explicit ID when provided")]
    public async Task HandleAsync_WithExplicitId_ReturnsExplicitId()
    {
        // Arrange
        var request = new CreateLearningComponentRequest(
            learningSpaceId: ValidLearningSpaceId,
            width: 1.5f,
            height: 1.0f,
            depth: 0.5f,
            x: 10.0f,
            y: 5.0f,
            z: 0.0f,
            orientation: "North",
            componentId: ExplicitComponentId);

        var serviceResult = new CreateComponentResult(ExplicitComponentId);

        _mockService
            .Setup(s => s.CreateComponentAsync(It.Is<CreateComponentRequest>(r => r.ComponentId == ExplicitComponentId)))
            .ReturnsAsync(serviceResult);

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, request);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result, Is.TypeOf<Ok<CreateLearningComponentResponse>>())
                .Or.TypeOf<Created<CreateLearningComponentResponse>>();
            var successResult = result as Ok<CreateLearningComponentResponse>;
            if (successResult != null)
            {
                Assert.That(successResult.Value!.ComponentId, Is.EqualTo(ExplicitComponentId));
            }
        });
    }

    /// <summary>
    /// Presentation-003: Verify that attempting to create a component with a duplicate ID returns a 409 Conflict response.
    /// </summary>
    [Test]
    [Description("Presentation-003: Verify handler returns 409 Conflict for duplicate ID")]
    public async Task HandleAsync_WithDuplicateId_ReturnsConflict()
    {
        // Arrange
        var request = new CreateLearningComponentRequest(
            learningSpaceId: ValidLearningSpaceId,
            width: 1.5f,
            height: 1.0f,
            depth: 0.5f,
            x: 10.0f,
            y: 5.0f,
            z: 0.0f,
            orientation: "North",
            componentId: "COMP-DUPLICATE");

        _mockService
            .Setup(s => s.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new DuplicateIdException("already exists"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, request);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result, Is.TypeOf<Conflict<ErrorResponse>>())
                .Or.TypeOf<ProblemHttpResult>();
            var conflictResult = result as Conflict<ErrorResponse>;
            if (conflictResult != null)
            {
                Assert.That(conflictResult.Value!.Message, Does.Contain("already exists"));
            }
        });
    }

    /// <summary>
    /// Presentation-004: Verify that creating a component with invalid data returns a 400 Bad Request response.
    /// </summary>
    [Test]
    [Description("Presentation-004: Verify handler returns 400 Bad Request for invalid data")]
    public async Task HandleAsync_WithInvalidData_ReturnsBadRequest()
    {
        // Arrange
        var request = new CreateLearningComponentRequest(
            learningSpaceId: ValidLearningSpaceId,
            width: -1.5f,
            height: 1.0f,
            depth: 0.5f,
            x: 10.0f,
            y: 5.0f,
            z: 0.0f,
            orientation: "North",
            componentId: null);

        _mockService
            .Setup(s => s.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new ValidationException("Width must be positive"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, request);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result, Is.TypeOf<BadRequest<ErrorResponse>>())
                .Or.TypeOf<ValidationProblem>();
            var badRequestResult = result as BadRequest<ErrorResponse>;
            if (badRequestResult != null)
            {
                Assert.That(badRequestResult.Value!.Message, Does.Contain("Width"));
            }
        });
    }
}

/// <summary>
/// Request DTO for creating a learning component.
/// </summary>
public class CreateLearningComponentRequest
{
    public string LearningSpaceId { get; }
    public float Width { get; }
    public float Height { get; }
    public float Depth { get; }
    public float X { get; }
    public float Y { get; }
    public float Z { get; }
    public string Orientation { get; }
    public string? ComponentId { get; }

    public CreateLearningComponentRequest(
        string learningSpaceId,
        float width,
        float height,
        float depth,
        float x,
        float y,
        float z,
        string orientation,
        string? componentId)
    {
        LearningSpaceId = learningSpaceId;
        Width = width;
        Height = height;
        Depth = depth;
        X = x;
        Y = y;
        Z = z;
        Orientation = orientation;
        ComponentId = componentId;
    }
}

/// <summary>
/// Response DTO for creating a learning component.
/// </summary>
public class CreateLearningComponentResponse
{
    public string ComponentId { get; }
    public string Message { get; }

    public CreateLearningComponentResponse(string componentId, string message)
    {
        ComponentId = componentId;
        Message = message;
    }
}

/// <summary>
/// Error response DTO.
/// </summary>
public class ErrorResponse
{
    public string Message { get; }

    public ErrorResponse(string message)
    {
        Message = message;
    }
}

/// <summary>
/// Exception thrown when attempting to create an entity with a duplicate ID.
/// </summary>
public class DuplicateIdException : Exception
{
    public DuplicateIdException(string message) : base(message) { }
}

/// <summary>
/// Exception thrown when validation fails.
/// </summary>
public class ValidationException : Exception
{
    public ValidationException(string message) : base(message) { }
}

/// <summary>
/// Result object returned after creating a learning component.
/// </summary>
public class CreateComponentResult
{
    public string ComponentId { get; }

