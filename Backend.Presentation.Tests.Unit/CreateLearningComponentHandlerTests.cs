using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Http.HttpResults;
using Moq;
using NUnit.Framework;
using UCR.ECCI.PI.ThemePark.Backend.Application.Services;
using UCR.ECCI.PI.ThemePark.Backend.Domain.Entities;
using UCR.ECCI.PI.ThemePark.Backend.Domain.Exceptions;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Handlers;

namespace UCR.ECCI.PI.ThemePark.Backend.Presentation.Tests.Unit;

/// <summary>
/// Unit tests for <see cref="CreateLearningComponentHandler.HandleAsync"/>.
/// Covers CPD-LC-001-009 Presentation-001 through Presentation-004.
/// </summary>
[TestFixture]
public class CreateLearningComponentHandlerTests
{
    private Mock<ILearningComponentService> _mockService = null!;
    private CreateLearningComponentHandler _sut = null!;

    [SetUp]
    public void SetUp()
    {
        _mockService = new Mock<ILearningComponentService>();
        _sut = new CreateLearningComponentHandler(_mockService.Object);
    }

    [TearDown]
    public void TearDown()
    {
        _mockService.VerifyAll();
    }

    private static CreateComponentRequest CreateValidRequest(string? componentId = null)
    {
        return new CreateComponentRequest(
            ComponentId: componentId,
            LearningSpaceId: "LS-001",
            Width: 1.5f,
            Height: 1.0f,
            Depth: 0.5f,
            X: 10.0f,
            Y: 5.0f,
            Z: 0.0f,
            Orientation: "North");
    }

    /// <summary>
    /// CPD-LC-001-009 Presentation-001: Verify that creating a component without an ID
    /// returns the auto-generated ID in the response.
    /// </summary>
    [Test]
    [Description("CPD-LC-001-009 Presentation-001: Handler returns auto-generated ID when no ID provided")]
    public async Task HandleAsync_WithoutId_ReturnsAutoGeneratedId()
    {
        // Arrange
        var generatedId = "COMP-12345";
        var request = CreateValidRequest(componentId: null);
        var component = new LearningComponent(
            generatedId, "LS-001", 1.5f, 1.0f, 0.5f, 10.0f, 5.0f, 0.0f, "North");

        _mockService
            .Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ReturnsAsync(component);

        // Act
        var result = await _sut.HandleAsync(request);

        // Assert
        Assert.That(result.ComponentId, Is.EqualTo(generatedId));
    }

    /// <summary>
    /// CPD-LC-001-009 Presentation-002: Verify that creating a component with an explicit ID
    /// returns the provided ID in the response.
    /// </summary>
    [Test]
    [Description("CPD-LC-001-009 Presentation-002: Handler returns explicit ID when provided")]
    public async Task HandleAsync_WithExplicitId_ReturnsProvidedId()
    {
        // Arrange
        var explicitId = "COMP-EXPLICIT-001";
        var request = CreateValidRequest(componentId: explicitId);
        var component = new LearningComponent(
            explicitId, "LS-001", 1.5f, 1.0f, 0.5f, 10.0f, 5.0f, 0.0f, "North");

        _mockService
            .Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ReturnsAsync(component);

        // Act
        var result = await _sut.HandleAsync(request);

        // Assert
        Assert.That(result.ComponentId, Is.EqualTo(explicitId));
    }

    /// <summary>
    /// CPD-LC-001-009 Presentation-003: Verify that attempting to create a component
    /// with a duplicate ID returns a 409 Conflict response.
    /// </summary>
    [Test]
    [Description("CPD-LC-001-009 Presentation-003: Handler returns 409 Conflict for duplicate ID")]
    public async Task HandleAsync_DuplicateId_Returns409Conflict()
    {
        // Arrange
        var request = CreateValidRequest(componentId: "COMP-EXISTING");

        _mockService
            .Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new DuplicateIdException("Component with ID 'COMP-EXISTING' already exists"));

        // Act
        var result = await _sut.HandleAsync(request);

        // Assert
        Assert.That(result.StatusCode, Is.EqualTo(409));
    }

    /// <summary>
    /// CPD-LC-001-009 Presentation-004: Verify that creating a component with invalid data
    /// returns a 400 Bad Request response.
    /// </summary>
    [Test]
    [Description("CPD-LC-001-009 Presentation-004: Handler returns 400 Bad Request for invalid data")]
    public async Task HandleAsync_InvalidData_Returns400BadRequest()
    {
        // Arrange
        var request = new CreateComponentRequest(
            ComponentId: null,
            LearningSpaceId: "LS-001",
            Width: -1.5f,
            Height: 1.0f,
            Depth: 0.5f,
            X: 10.0f,
            Y: 5.0f,
            Z: 0.0f,
            Orientation: "North");

        _mockService
            .Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new ValidationException("Width must be positive"));

        // Act
        var result = await _sut.HandleAsync(request);

        // Assert
        Assert.That(result.StatusCode, Is.EqualTo(400));
    }
}
