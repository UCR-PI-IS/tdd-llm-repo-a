using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Http.HttpResults;
using Moq;
using NUnit.Framework;
using UCR.ECCI.PI.ThemePark.Backend.Application.Services;
using UCR.ECCI.PI.ThemePark.Backend.Domain.Exceptions;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Dtos;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Handlers;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Responses;

namespace UCR.ECCI.PI.ThemePark.Backend.Presentation.Tests.Unit;

/// <summary>
/// Unit tests for <see cref="CreateLearningComponentHandler.HandleAsync"/>.
/// Covers intents Presentation-001 through Presentation-004 for CPD-LC-001-009.
/// </summary>
[TestFixture]
public class CreateLearningComponentHandlerTests
{
    private Mock<ILearningComponentService> _mockService = null!;

    // Valid test data
    private const string ValidLearningSpaceId = "LS-001";
    private const float ValidWidth = 1.5f;
    private const float ValidHeight = 1.0f;
    private const float ValidDepth = 0.5f;
    private const float ValidX = 10.0f;
    private const float ValidY = 5.0f;
    private const float ValidZ = 0.0f;
    private const string ValidOrientation = "North";

    [SetUp]
    public void SetUp()
    {
        _mockService = new Mock<ILearningComponentService>();
    }

    [TearDown]
    public void TearDown()
    {
        _mockService.VerifyAll();
    }

    /// <summary>
    /// Presentation-001: Verify that creating a component without an ID returns the auto-generated ID in the response.
    /// </summary>
    [Test]
    [Description("Presentation-001: Verify that creating a component without an ID returns the auto-generated ID in the response")]
    public async Task HandleAsync_WithoutId_ReturnsAutoGeneratedId()
    {
        // Arrange
        var generatedId = "COMP-12345";
        var request = new CreateComponentRequest(
            ValidLearningSpaceId, ValidWidth, ValidHeight, ValidDepth, ValidX, ValidY, ValidZ, ValidOrientation);

        _mockService
            .Setup(x => x.CreateComponentAsync(It.Is<CreateComponentRequest>(r =>
                r.LearningSpaceId == ValidLearningSpaceId &&
                r.ComponentId == null)))
            .ReturnsAsync(new CreateComponentResponse(generatedId, true));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, request);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result, Is.TypeOf<Ok<CreateLearningComponentResponse>>());
            var okResult = result as Ok<CreateLearningComponentResponse>;
            Assert.That(okResult!.Value!.ComponentId, Is.EqualTo(generatedId));
            Assert.That(okResult.Value.Message, Does.Contain("auto-generated"));
        });
    }

    /// <summary>
    /// Presentation-002: Verify that creating a component with an explicit ID returns the provided ID in the response.
    /// </summary>
    [Test]
    [Description("Presentation-002: Verify that creating a component with an explicit ID returns the provided ID in the response")]
    public async Task HandleAsync_WithExplicitId_ReturnsProvidedId()
    {
        // Arrange
        var explicitId = "COMP-EXPLICIT-001";
        var request = new CreateComponentRequest(
            explicitId, ValidLearningSpaceId, ValidWidth, ValidHeight, ValidDepth, ValidX, ValidY, ValidZ, ValidOrientation);

        _mockService
            .Setup(x => x.CreateComponentAsync(It.Is<CreateComponentRequest>(r =>
                r.ComponentId == explicitId)))
            .ReturnsAsync(new CreateComponentResponse(explicitId, false));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, request);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result, Is.TypeOf<Ok<CreateLearningComponentResponse>>());
            var okResult = result as Ok<CreateLearningComponentResponse>;
            Assert.That(okResult!.Value!.ComponentId, Is.EqualTo(explicitId));
        });
    }

    /// <summary>
    /// Presentation-003: Verify that attempting to create a component with a duplicate ID returns a 409 Conflict response.
    /// </summary>
    [Test]
    [Description("Presentation-003: Verify that attempting to create a component with a duplicate ID returns a 409 Conflict response")]
    public async Task HandleAsync_DuplicateId_ReturnsConflict()
    {
        // Arrange
        var duplicateId = "COMP-DUPLICATE";
        var request = new CreateComponentRequest(
            duplicateId, ValidLearningSpaceId, ValidWidth, ValidHeight, ValidDepth, ValidX, ValidY, ValidZ, ValidOrientation);

        _mockService
            .Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new DuplicateIdException($"Component with ID '{duplicateId}' already exists"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, request);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result, Is.TypeOf<Conflict<ErrorResponse>>());
            var conflictResult = result as Conflict<ErrorResponse>;
            Assert.That(conflictResult!.Value!.Message, Does.Contain("already exists"));
        });
    }

    /// <summary>
    /// Presentation-004: Verify that creating a component with invalid data returns a 400 Bad Request response.
    /// </summary>
    [Test]
    [Description("Presentation-004: Verify that creating a component with invalid data returns a 400 Bad Request response")]
    public async Task HandleAsync_InvalidData_ReturnsBadRequest()
    {
        // Arrange
        var request = new CreateComponentRequest(
            ValidLearningSpaceId, -1.5f, ValidHeight, ValidDepth, ValidX, ValidY, ValidZ, ValidOrientation);

        _mockService
            .Setup(x => x.CreateComponentAsync(It.IsAny<CreateComponentRequest>()))
            .ThrowsAsync(new ValidationException("Width must be positive"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, request);

        // Assert
        Assert.Multiple(() =>
        {
            Assert.That(result, Is.TypeOf<BadRequest<ErrorResponse>>());
            var badRequestResult = result as BadRequest<ErrorResponse>;
            Assert.That(badRequestResult!.Value!.Message, Does.Contain("Width"));
        });
    }
}
