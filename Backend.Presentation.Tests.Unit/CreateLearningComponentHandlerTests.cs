using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Http.HttpResults;
using Moq;
using NUnit.Framework;
using UCR.ECCI.PI.ThemePark.Backend.Application.Exceptions;
using UCR.ECCI.PI.ThemePark.Backend.Application.Services;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Handlers;
using UCR.ECCI.PI.ThemePark.Backend.Presentation.Api.Responses;

namespace UCR.ECCI.PI.ThemePark.Backend.Presentation.Tests.Unit;

/// <summary>
/// Unit tests for <see cref="CreateLearningComponentHandler.HandleAsync"/>.
/// Covers Presentation-001 through Presentation-004.
/// </summary>
[TestFixture]
public class CreateLearningComponentHandlerTests
{
    private Mock<ILearningComponentService> _mockService = null!;

    [SetUp]
    public void SetUp()
    {
        _mockService = new Mock<ILearningComponentService>();
    }

    [TearDown]
    public void TearDown()
    {
        _mockService.VerifyAll();
    }

    /// <summary>
    /// Presentation-001: Verify handler returns Created with auto-generated ID when no ID is provided.
    /// </summary>
    [Test]
    [Description("Presentation-001: Verify handler returns Created with auto-generated ID")]
    public async Task HandleAsync_WithoutId_ReturnsCreatedWithAutoGeneratedId()
    {
        // Arrange
        var request = new CreateComponentRequest
        {
            LearningSpaceId = "LS-001",
            Width = 1.5f,
            Height = 1.0f,
            Depth = 0.5f,
            X = 10f,
            Y = 5f,
            Z = 0f,
            Orientation = "North"
        };

        _mockService
            .Setup(s => s.CreateComponentAsync(request))
            .ReturnsAsync(new CreateComponentResult("COMP-12345", "Component created with auto-generated ID"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, request);

        // Assert
        Assert.That(result, Is.TypeOf<Created<CreateComponentResponse>>());
        var createdResult = (Created<CreateComponentResponse>)result;
        Assert.Multiple(() =>
        {
            Assert.That(createdResult.Value.ComponentId, Is.EqualTo("COMP-12345"));
            Assert.That(createdResult.Value.Message, Does.Contain("auto-generated"));
        });
    }

    /// <summary>
    /// Presentation-002: Verify handler returns Created with the explicit provided ID.
    /// </summary>
    [Test]
    [Description("Presentation-002: Verify handler returns Created with explicit provided ID")]
    public async Task HandleAsync_WithExplicitId_ReturnsCreatedWithProvidedId()
    {
        // Arrange
        var request = new CreateComponentRequest
        {
            ComponentId = "COMP-EXPLICIT-001",
            LearningSpaceId = "LS-001",
            Width = 1.5f,
            Height = 1.0f,
            Depth = 0.5f,
            X = 10f,
            Y = 5f,
            Z = 0f,
            Orientation = "North"
        };

        _mockService
            .Setup(s => s.CreateComponentAsync(request))
            .ReturnsAsync(new CreateComponentResult("COMP-EXPLICIT-001", "Component created"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, request);

        // Assert
        Assert.That(result, Is.TypeOf<Created<CreateComponentResponse>>());
        var createdResult = (Created<CreateComponentResponse>)result;
        Assert.That(createdResult.Value.ComponentId, Is.EqualTo("COMP-EXPLICIT-001"));
    }

    /// <summary>
    /// Presentation-003: Verify handler returns Conflict when duplicate ID is detected.
    /// </summary>
    [Test]
    [Description("Presentation-003: Verify handler returns Conflict for duplicate ID")]
    public async Task HandleAsync_WithDuplicateId_ReturnsConflict()
    {
        // Arrange
        var request = new CreateComponentRequest
        {
            ComponentId = "COMP-DUPLICATE",
            LearningSpaceId = "LS-001",
            Width = 1.5f,
            Height = 1.0f,
            Depth = 0.5f,
            X = 10f,
            Y = 5f,
            Z = 0f,
            Orientation = "North"
        };

        _mockService
            .Setup(s => s.CreateComponentAsync(request))
            .ThrowsAsync(new DuplicateIdException("already exists"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, request);

        // Assert
        Assert.That(result, Is.TypeOf<Conflict<ErrorResponse>>());
        var conflictResult = (Conflict<ErrorResponse>)result;
        Assert.Multiple(() =>
        {
            Assert.That(((IStatusCodeHttpResult)conflictResult).StatusCode, Is.EqualTo(409));
            Assert.That(conflictResult.Value.Message, Does.Contain("already exists"));
        });
    }

    /// <summary>
    /// Presentation-004: Verify handler returns Bad Request when invalid data is provided.
    /// </summary>
    [Test]
    [Description("Presentation-004: Verify handler returns BadRequest for invalid data")]
    public async Task HandleAsync_WithInvalidData_ReturnsBadRequest()
    {
        // Arrange
        var request = new CreateComponentRequest
        {
            LearningSpaceId = "LS-001",
            Width = -1.5f,
            Height = 1.0f,
            Depth = 0.5f,
            X = 10f,
            Y = 5f,
            Z = 0f,
            Orientation = "North"
        };

        _mockService
            .Setup(s => s.CreateComponentAsync(request))
            .ThrowsAsync(new ValidationException("Width must be positive"));

        // Act
        var result = await CreateLearningComponentHandler.HandleAsync(_mockService.Object, request);

        // Assert
        Assert.That(result, Is.TypeOf<BadRequest<ErrorResponse>>());
        var badRequestResult = (BadRequest<ErrorResponse>)result;
        Assert.Multiple(() =>
        {
            Assert.That(((IStatusCodeHttpResult)badRequestResult).StatusCode, Is.EqualTo(400));
            Assert.That(badRequestResult.Value.Message, Does.Contain("Width"));
        });
    }
}
